def strip_ids(txt: str, ids: list[str]) -> str:
    """删掉本脚本负责的那些 K-B 块（到下一个 ### 或 ## 为止），保证可重跑。"""
    for i in ids:
        txt = re.sub(rf"^### {re.escape(i)}\b.*?(?=^### |^## |\Z)", "",
                     txt, flags=re.S | re.M)
    return re.sub(r"\n{3,}", "\n\n", txt)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()

    by_hero: dict[str, list[dict]] = {}
    for e in ENTRIES:
        # 「对蒙恬：…」→ 对手名，写进「针对对手」字段
        m = re.match(r"对([^：:]+)[：:]", e["title"])
        opp = m.group(1) if m else ""
        e["opp"] = opp
        by_hero.setdefault(e["hero"], []).append(e)

    wrote = 0
    for hero, items in by_hero.items():
        p = KB / f"{hero}.md"
        if not p.exists():
            print(f"  [skip] {hero} 没有 B 卡", file=sys.stderr)
            continue
        txt = p.read_text(encoding="utf-8")
        body = "\n".join(render(e) for e in items)

        # ① 先剥掉旧的同编号块（幂等）
        txt = strip_ids(txt, [e["id"] for e in items])
        # ② 占位句还在就替掉它
        txt = txt.replace(PLACEHOLDER + "\n", "")
        # ③ 统一插在「## 实测条目」标题后面
        if "## 实测条目" not in txt:
            txt = txt.replace("\n## 待补", "\n## 实测条目\n\n## 待补", 1)
        txt = txt.replace("## 实测条目\n\n", "## 实测条目\n\n" + body + "\n", 1)
        txt = re.sub(r"\n{3,}", "\n\n", txt)
        wrote += 1
        if not args.dry:
            p.write_text(txt, encoding="utf-8")

    print(f"写入 {wrote} 个英雄卡，共 {len(ENTRIES)} 条 K-B 条目（幂等，可重跑）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
